// Expo config plugin: what Android's automatic backup (Google cloud backup) and phone-to-phone
// transfer copy to a new phone.
//
// Without our own rules, expo-secure-store installs rules that list only SharedPreferences. A rules
// file with an <include> backs up nothing else, so every activity file and the AsyncStorage database
// (settings, profile, gear, wellness log, activity index) were silently left out. app.json therefore
// sets expo-secure-store's `configureAndroidBackup: false` and this plugin points the manifest at:
//   - tbdi-data/ (src/lib/blobStore.ts): every activity and the list summaries, but not the live
//     recording (session.json): a restored phone must not resume a stale recording.
//   - the AsyncStorage database RKStorage (Android adds its -journal / -wal files itself).
// SharedPreferences are not included. Ours hold nothing but module state that is wrong on another phone:
// SecureStore (encrypted with a Keystore key that never leaves the old phone, so a copy is unreadable),
// expo-modules-core's "permission already asked" cache (would mark never-asked permissions as blocked),
// expo-notifications' list of scheduled reminders (the alarms themselves are not restored, so the app
// would think they exist and never reschedule them) and expo-task-manager's registered tasks.
//
// Google's cloud backup holds at most 25 MB per app; once the included data is bigger, Android skips the
// app's cloud backup completely and says nothing. Phone-to-phone transfer has no such cap. The in-app
// backup (Settings → Backup, GitHub cloud backup) stays the dependable way to keep the full history.
//
// Android 12+ reads android:dataExtractionRules (separate cloud / transfer lists), Android 11 and
// older read android:fullBackupContent.
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const BACKUP_RULES = 'tbdi_backup_rules';
const EXTRACTION_RULES = 'tbdi_data_extraction_rules';

const RULES = [
  '<include domain="file" path="tbdi-data" />',
  '<exclude domain="file" path="tbdi-data/session.json" />',
  '<exclude domain="file" path="tbdi-data/session.json.tmp" />',
  '<include domain="database" path="RKStorage" />',
  // nothing from SharedPreferences is included; this keeps SecureStore out even if that changes
  '<exclude domain="sharedpref" path="SecureStore" />',
];

const indent = (lines, pad) => lines.map((l) => pad + l).join('\n');
const header = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by plugins/withBackupRules.js; edit that file, not this one. -->\n';

const backupXml = `${header}<full-backup-content>\n${indent(RULES, '  ')}\n</full-backup-content>\n`;
const extractionXml = `${header}<data-extraction-rules>
  <cloud-backup>
${indent(RULES, '    ')}
  </cloud-backup>
  <device-transfer>
${indent(RULES, '    ')}
  </device-transfer>
</data-extraction-rules>
`;

function withBackupRuleFiles(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
    await fs.promises.mkdir(dir, { recursive: true });
    await fs.promises.writeFile(path.join(dir, `${BACKUP_RULES}.xml`), backupXml);
    await fs.promises.writeFile(path.join(dir, `${EXTRACTION_RULES}.xml`), extractionXml);
    return cfg;
  }]);
}

function withBackupRulesManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    app.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    return cfg;
  });
}

module.exports = function withBackupRules(config) {
  return withBackupRulesManifest(withBackupRuleFiles(config));
};
