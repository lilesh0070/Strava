// Copies Leaflet's compiled JS + CSS from node_modules into src/lib/leafletSrc.ts, so the map page in the
// WebView is self-contained: the route and position dot draw with no internet (only the street tiles need
// data). Run after bumping the leaflet devDependency: `node scripts/vendor-leaflet.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
const pkg = JSON.parse(readFileSync('node_modules/leaflet/package.json', 'utf8'));
const js = readFileSync('node_modules/leaflet/dist/leaflet.js', 'utf8');
if (js.includes('</script>')) throw new Error('leaflet.js contains </script>; cannot be inlined');
// the only images are the layers control and the default marker icon, which the app never uses
const css = readFileSync('node_modules/leaflet/dist/leaflet.css', 'utf8').replace(/url\(images\/[^)]*\)/g, 'none');
writeFileSync('src/lib/leafletSrc.ts', `// Generated by scripts/vendor-leaflet.mjs from leaflet@${pkg.version} (BSD-2-Clause). Do not edit.
export const LEAFLET_VERSION = ${JSON.stringify(pkg.version)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
export const LEAFLET_JS = ${JSON.stringify(js)};
`);
console.log(`src/lib/leafletSrc.ts written from leaflet@${pkg.version}: js ${js.length} B, css ${css.length} B`);
